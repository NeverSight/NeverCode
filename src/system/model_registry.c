#define MODEL_COUNT NC_ARRAY_LEN(MODELS)

/* ── Provider prefix normalization ──
 * Handles "provider:model" syntax (e.g. "openrouter:gpt-5.4", "local:llama3").
 * Only recognized provider tags are stripped; Ollama-style "model:tag" patterns
 * (e.g. "qwen3:27b", "llama3:latest") are preserved. */

static const char *const KNOWN_PROVIDER_PREFIXES[] = {
    "openrouter", "anthropic", "openai", "deepseek", "google",  "local",   "custom",
    "nous",       "copilot",   "kimi",   "moonshot", "minimax", "alibaba", "qwen",
    "dashscope",  "aliyun",    "vercel", "github",   NULL,
};

static bool is_ollama_tag(const char *tag) {
    if (!tag || !*tag)
        return false;
    if (strncasecmp(tag, "latest", 6) == 0)
        return true;
    if (strncasecmp(tag, "stable", 6) == 0)
        return true;
    if ((*tag >= '0' && *tag <= '9') || *tag == 'q' || *tag == 'f')
        return true;
    if (strncasecmp(tag, "instruct", 8) == 0 || strncasecmp(tag, "chat", 4) == 0 ||
        strncasecmp(tag, "coder", 5) == 0 || strncasecmp(tag, "vision", 6) == 0)
        return true;
    return false;
}

static const char *strip_provider_prefix(const char *name, char *buf, size_t buf_sz) {
    if (!name)
        return name;
    const char *colon = strchr(name, ':');
    if (!colon || name[0] == 'h') /* skip http:// */
        return name;
    size_t prefix_len = (size_t)(colon - name);
    const char *suffix = colon + 1;
    if (is_ollama_tag(suffix))
        return name;
    for (const char *const *p = KNOWN_PROVIDER_PREFIXES; *p; p++) {
        if (prefix_len == strlen(*p) && strncasecmp(name, *p, prefix_len) == 0) {
            nc_strlcpy(buf, suffix, buf_sz);
            return buf;
        }
    }
    return name;
}

/* ── Lookup ── */

const model_info_t *model_registry_find(const char *id) {
    if (!id)
        return NULL;
    char normalized[MODEL_NAME_MAX];
    const char *lookup = strip_provider_prefix(id, normalized, sizeof(normalized));
    for (int i = 0; i < MODEL_COUNT; i++) {
        if (MODELS[i].id && strcmp(MODELS[i].id, lookup) == 0)
            return &MODELS[i];
    }
    return NULL;
}

const model_info_t *model_registry_match(const char *name) {
    if (!name)
        return NULL;
    char normalized[MODEL_NAME_MAX];
    const char *lookup = strip_provider_prefix(name, normalized, sizeof(normalized));
    for (int i = 0; i < MODEL_COUNT; i++) {
        if (strcasestr(lookup, MODELS[i].pattern))
            return &MODELS[i];
    }
    return NULL;
}

int model_registry_count(void) {
    return MODEL_COUNT;
}

const model_info_t *model_registry_get(int index) {
    if (index < 0 || index >= MODEL_COUNT)
        return NULL;
    return &MODELS[index];
}

int model_registry_by_provider(const char *owned_by, const model_info_t **out, int max) {
    if (!owned_by || !out || max <= 0)
        return 0;
    int n = 0;
    for (int i = 0; i < MODEL_COUNT && n < max; i++) {
        if (MODELS[i].owned_by && strcasecmp(MODELS[i].owned_by, owned_by) == 0)
            out[n++] = &MODELS[i];
    }
    return n;
}

int model_registry_input_limit(const char *model) {
    const model_info_t *m = model_registry_match(model);
    if (!m)
        return DEFAULT_CONTEXT_FALLBACK - DEFAULT_MAX_TOKENS;
    if (m->max_input_tokens > 0)
        return m->max_input_tokens;
    return m->context_length - m->max_output_tokens;
}

double model_registry_input_price(const char *model) {
    const model_info_t *m = model_registry_match(model);
    if (m && m->price_input > 0)
        return m->price_input;
    return COST_DEFAULT_INPUT;
}

double model_registry_output_price(const char *model) {
    const model_info_t *m = model_registry_match(model);
    if (m && m->price_output > 0)
        return m->price_output;
    return COST_DEFAULT_OUTPUT;
}

double model_registry_cache_read_price(const char *model) {
    const model_info_t *m = model_registry_match(model);
    if (m) {
        if (m->price_cache_read > 0)
            return m->price_cache_read;
        double base = m->price_input > 0 ? m->price_input : COST_DEFAULT_INPUT;
        if (m->owned_by && strcasecmp(m->owned_by, "anthropic") == 0)
            return base * CACHE_READ_DISCOUNT_ANTH;
        return base * CACHE_READ_DISCOUNT_DEFAULT;
    }
    return COST_DEFAULT_INPUT * CACHE_READ_DISCOUNT_DEFAULT;
}

double model_registry_cache_write_price(const char *model) {
    const model_info_t *m = model_registry_match(model);
    if (m) {
        if (m->price_cache_write > 0)
            return m->price_cache_write;
        double base = m->price_input > 0 ? m->price_input : COST_DEFAULT_INPUT;
        if (m->owned_by && strcasecmp(m->owned_by, "anthropic") == 0)
            return base * CACHE_WRITE_MULT_ANTH;
        return base;
    }
    return COST_DEFAULT_INPUT;
}
