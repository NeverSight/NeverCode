bool nc_project_doc_is_filename(const char *base) {
    if (!base || !*base)
        return false;
    for (int i = 0; i < nc_project_doc_leaf_n; i++) {
        if (strcmp(base, nc_project_doc_leaf_names[i]) == 0)
            return true;
    }
    return false;
}
