static int visible_len(const char *s, int n) {
    int vis = 0;
    bool in_esc = false;
    for (int i = 0; i < n && s[i];) {
        if (s[i] == '\033') {
            in_esc = true;
            i++;
            continue;
        }
        if (in_esc) {
            if (isalpha((unsigned char)s[i]))
                in_esc = false;
            i++;
            continue;
        }
        int adv = 1;
        unsigned int cp = decode_utf8_char((const unsigned char *)s + i, n - i, &adv);
        vis += unicode_cell_width(cp);
        i += adv;
    }
    return vis;
}

static int find_break(const char *line, int len, int width) {
    int vis = 0;
    int last_space = -1;
    bool in_esc = false;

    for (int i = 0; i < len;) {
        if (line[i] == '\033') {
            in_esc = true;
            i++;
            continue;
        }
        if (in_esc) {
            if (isalpha((unsigned char)line[i]))
                in_esc = false;
            i++;
            continue;
        }
        int adv = 1;
        unsigned int cp = decode_utf8_char((const unsigned char *)line + i, len - i, &adv);
        if (cp == ' ' || cp == '\t')
            last_space = i;
        int cell_width = unicode_cell_width(cp);
        if (vis + cell_width > width)
            return (last_space > 0) ? last_space + 1 : (i > 0 ? i : i + adv);
        vis += cell_width;
        i += adv;
        if (vis >= width) {
            return (last_space > 0) ? last_space + 1 : i;
        }
    }
    return len;
}

char *line_wrap(const char *text, int width) {
    if (!text)
        return NULL;
    if (width <= 0)
        width = LWRAP_DEFAULT_WIDTH;

    strbuf_t sb;
    strbuf_init(&sb);

    const char *p = text;
    while (*p) {
        const char *nl = strchr(p, '\n');
        int seg_len = nl ? (int)(nl - p) : (int)strlen(p);
        int seg_vis = visible_len(p, seg_len);

        if (seg_vis <= width) {
            strbuf_append(&sb, p, (size_t)seg_len);
            if (nl) {
                strbuf_append_str(&sb, "\n");
                p = nl + 1;
            } else
                break;
            continue;
        }

        const char *seg = p;
        int remaining = seg_len;
        while (remaining > 0) {
            int brk = find_break(seg, remaining, width);
            strbuf_append(&sb, seg, (size_t)brk);
            seg += brk;
            remaining -= brk;
            if (remaining > 0)
                strbuf_append_str(&sb, "\n");
        }

        if (nl) {
            strbuf_append_str(&sb, "\n");
            p = nl + 1;
        } else
            break;
    }

    return strbuf_detach(&sb);
}

int line_wrap_count(const char *text, int width) {
    if (!text || !*text)
        return 0;
    if (width <= 0)
        width = LWRAP_DEFAULT_WIDTH;

    int lines = 0;
    const char *p = text;
    while (*p) {
        const char *nl = strchr(p, '\n');
        int seg_len = nl ? (int)(nl - p) : (int)strlen(p);
        int seg_vis = visible_len(p, seg_len);
        lines += (seg_vis + width - 1) / width;
        if (lines == 0)
            lines = 1;
        if (nl)
            p = nl + 1;
        else
            break;
    }
    return lines;
}

int line_visible_width(const char *line) {
    if (!line)
        return 0;
    return visible_len(line, (int)strlen(line));
}

void line_copy_prefix_cells(const char *src, int max_cells, char *out, size_t out_sz) {
    size_t w = 0;
    int cells = 0;
    size_t i = 0;
    if (!src || !out || out_sz == 0)
        return;
    size_t slen = strlen(src);
    while (src[i] && cells < max_cells && w < out_sz - 1) {
        if (src[i] == '\033') {
            size_t esc_start = i;
            i++;
            while (i < slen && !isalpha((unsigned char)src[i]))
                i++;
            if (i < slen)
                i++;
            size_t esc_len = i - esc_start;
            if (w + esc_len < out_sz) {
                memcpy(out + w, src + esc_start, esc_len);
                w += esc_len;
            }
            continue;
        }
        int adv = 1;
        unsigned int cp = decode_utf8_char((const unsigned char *)src + i, (int)(slen - i), &adv);
        int cw = unicode_cell_width(cp);
        if (cw > 0 && cells + cw > max_cells)
            break;
        if (w + (size_t)adv >= out_sz)
            break;
        memcpy(out + w, src + i, (size_t)adv);
        w += (size_t)adv;
        i += (size_t)adv;
        cells += cw;
    }
    out[w] = '\0';
}
