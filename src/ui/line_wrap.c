/*
 * line_wrap.c — smart text line wrapping
 *
 * Word-aware wrapping for terminal output. Handles ANSI escape
 * sequences transparently (they don't count toward visible width).
 */

#include "nevercode.h"
#include "defaults.h"

typedef struct {
    unsigned int first;
    unsigned int last;
} unicode_range_t;

static unsigned int decode_utf8_char(const unsigned char *s, int remaining, int *adv) {
    unsigned char c = s[0];
    if (c < 0x80) {
        *adv = 1;
        return c;
    }
    if ((c & 0xE0) == 0xC0 && remaining >= 2 && (s[1] & 0xC0) == 0x80) {
        *adv = 2;
        return ((unsigned int)(c & 0x1F) << 6) | (unsigned int)(s[1] & 0x3F);
    }
    if ((c & 0xF0) == 0xE0 && remaining >= 3 && (s[1] & 0xC0) == 0x80 && (s[2] & 0xC0) == 0x80) {
        *adv = 3;
        return ((unsigned int)(c & 0x0F) << 12) | ((unsigned int)(s[1] & 0x3F) << 6) |
               (unsigned int)(s[2] & 0x3F);
    }
    if ((c & 0xF8) == 0xF0 && remaining >= 4 && (s[1] & 0xC0) == 0x80 && (s[2] & 0xC0) == 0x80 &&
        (s[3] & 0xC0) == 0x80) {
        *adv = 4;
        return ((unsigned int)(c & 0x07) << 18) | ((unsigned int)(s[1] & 0x3F) << 12) |
               ((unsigned int)(s[2] & 0x3F) << 6) | (unsigned int)(s[3] & 0x3F);
    }
    *adv = 1;
    return c;
}

static bool cp_in_ranges(unsigned int cp, const unicode_range_t *ranges, size_t nranges) {
    for (size_t i = 0; i < nranges; i++) {
        if (cp >= ranges[i].first && cp <= ranges[i].last)
            return true;
    }
    return false;
}

